ISO_3166_1_NAME_TO_CODE: dict[str, str] = {
    **{name: code for code, name in ISO_3166_1_ALPHA_2_TO_NAME.items()},
    **_NAME_TO_CODE_ALIASES,
}


def country_name(code: str) -> str | None:
    """ISO 3166-1 alpha-2 code to country name; None for unknown codes (e.g. TMDB-internal XC/XI)."""
    return ISO_3166_1_ALPHA_2_TO_NAME.get(code)


def country_code(name: str) -> str | None:
    """Country name to ISO 3166-1 alpha-2 code; None for unknown names."""
    return ISO_3166_1_NAME_TO_CODE.get(name)


def code_name_pairs(pairs: list[dict], code_key: str, name_key: str | None = None) -> list[dict]:
    """Normalize API responses into [{"code", "name"}] dicts, filling missing names from the ISO map."""
    result = []
    for item in pairs:
        code = item.get(code_key)
        if code is None:
            continue
        name = item.get(name_key) if name_key else None
        if not name:
            name = country_name(code)
        result.append({"code": code, "name": name})
    return result
